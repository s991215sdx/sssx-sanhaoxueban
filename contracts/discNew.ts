/**
 * 计分：most/least 为各 24 个词下标（0-3）。
 * 最像我 +1、最不像我 −1，按词因子归属汇总四轴；
 * 「三个我」调整规则为自研近似（原版未公开，见文件头注释）。
 */
export function scoreDiscNew(most: number[], least: number[], scene: DiscNewScene): DiscNewResult {
  if (most.length !== DISC_NEW_GROUP_COUNT || least.length !== DISC_NEW_GROUP_COUNT) {
    throw new Error(`DISC（新版）答案数量应为 ${DISC_NEW_GROUP_COUNT} 组，实际 most=${most.length} least=${least.length}`);
  }
  const net: Record<DiscNewFactor, number> = { D: 0, I: 0, S: 0, C: 0 };
  for (let i = 0; i < DISC_NEW_GROUP_COUNT; i++) {
    net[DISC_NEW_GROUPS[i].words[most[i]].f] += 1;
    net[DISC_NEW_GROUPS[i].words[least[i]].f] -= 1;
  }
  const pct = {} as Record<DiscNewFactor, number>;
  DISC_NEW_FACTORS.forEach((f) => (pct[f] = Math.round((net[f] / DISC_NEW_GROUP_COUNT) * 100)));
  const sceneScores: Record<DiscNewFactor, number> = {
    D: Math.round(net.D * 0.8),
    I: Math.round(net.I * 0.75),
    S: Math.round(net.S + net.I * 0.25),
    C: Math.round(net.C + net.D * 0.2),
  };
  const pressureScores: Record<DiscNewFactor, number> = {
    D: Math.round(net.D + net.S * 0.3 + net.I * 0.15),
    I: Math.round(net.I * 0.5),
    S: Math.round(net.S * 0.5),
    C: Math.round(net.C + net.S * 0.35 + net.I * 0.25),
  };
  const t = discNewTopTypes(net);
  return {
    version: "new",
    scene,
    primary: t.order[0],
    typeKey: t.typeKey,
    typeName: t.typeName,
    top: t.top,
    order: t.order,
    net,
    pct,
    sceneScores,
    pressureScores,
  };
}

/** 由净分/调整分算主分型：取所有正分因子前二（字母序拼组合），无正分则取最高分单型。 */
export function discNewTopTypes(p: Record<DiscNewFactor, number>): DiscNewTypeInfo {
  const order = DISC_NEW_FACTORS.slice().sort((a, b) => p[b] - p[a]);
  const hi = order.filter((f) => p[f] > 0);
  const top = hi.length ? hi.slice(0, 2) : order.slice(0, 1);
  const combo = top.slice(0, 2).sort().join("");
  return { order, typeKey: combo, typeName: DISC_NEW_TYPE_NAMES[combo] ?? `${DISC_NEW_TYPE_NAMES[top[0]]}型`, top };
}

/** 词库高亮：每因子按倾向符号取 4 词，强度带决定取词位置（|pct|<15 取前 4，15-29 取中 4，≥30 取后 4）。 */
export function discNewHlWords(f: DiscNewFactor, pctv: number): string[] {
  const bank = DISC_NEW_WORD_BANK[f];
  const arr = pctv >= 0 ? bank.pos : bank.neg;
  const band = Math.min(2, Math.floor(Math.abs(pctv) / 15));
  const start = band * 4;
  return arr.slice(start, start + 4);
}

/** 四轴图点位（0-100%）：净分 -24..24 映射到 0..100，最少留 2% 边距。 */
export function discNewAxisDots(val: number): number {
  return Math.max(2, Math.min(98, 50 + (val / DISC_NEW_GROUP_COUNT) * 50));
}
