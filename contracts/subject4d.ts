/** 维度分档：>=4 高；2.5~3.99 中；<2.5 低（解释文案按档取） */
export function subject4dBand(score: number): "高" | "中" | "低" {
  if (score >= 4) return "高";
  if (score >= 2.5) return "中";
  return "低";
}

/** 细分档（报告展示用）：4.5+ 高 / 3.5~4.49 中偏高 / 2.5~3.49 中 / 1.8~2.49 中偏低 / <1.8 低 */
export function subject4dBandLabel(score: number): string {
  if (score >= 4.5) return "高";
  if (score >= 3.5) return "中偏高";
  if (score >= 2.5) return "中";
  if (score >= 1.8) return "中偏低";
  return "低";
}

