/** 结果结构：submit 后存入 assessments.result（JSON） */
export interface Subject4dResult {
  /** 每科四维均分（1-5，保留两位） */
  subjects: Record<Subject4dName, { 兴趣: number; 能力倾向: number; 观念: number; 效能感: number; 潜力指数: number }>;
  /** 分档 */
  bands: Record<Subject4dName, { 兴趣: "高" | "中" | "低"; 能力倾向: "高" | "中" | "低"; 观念: "高" | "中" | "低"; 效能感: "高" | "中" | "低" }>;
  /** 原始作答：科目 → 12 个选项索引（0-4） */
  answers: Record<Subject4dName, number[]>;
  answeredAt: string;
}

/** 计分：answers[科目] = 12 个选项索引（与 SUBJECT4D_BANK[科目] 顺序一致） */
export function scoreSubject4d(answers: Record<string, number[]>): Subject4dResult {
  const subjects = {} as Subject4dResult["subjects"];
  const bands = {} as Subject4dResult["bands"];
  for (const name of SUBJECT4D_SUBJECTS) {
    const arr = answers[name];
    const items = SUBJECT4D_BANK[name];
    if (!arr || arr.length !== items.length) continue;
    const dimScores: Record<Subject4dDim, number> = { 兴趣: 0, 能力倾向: 0, 观念: 0, 效能感: 0 };
    const dimCounts: Record<Subject4dDim, number> = { 兴趣: 0, 能力倾向: 0, 观念: 0, 效能感: 0 };
    items.forEach((item, i) => {
      const opt = arr[i]!;
      const val = SUBJECT4D_SCORES[opt] ?? 3;
      dimScores[item.dim] += val;
      dimCounts[item.dim] += 1;
    });
    const dims = {} as Record<Subject4dDim, number>;
    let sum = 0;
    for (const d of SUBJECT4D_DIMS) {
      dims[d] = Math.round((dimScores[d] / Math.max(1, dimCounts[d])) * 100) / 100;
      sum += dims[d];
    }
    const potential = Math.round((sum / 4) * 100) / 100;
    subjects[name] = { ...dims, 潜力指数: potential };
    bands[name] = {
      兴趣: subject4dBand(dims.兴趣),
      能力倾向: subject4dBand(dims.能力倾向),
      观念: subject4dBand(dims.观念),
      效能感: subject4dBand(dims.效能感),
    };
  }
  return { subjects, bands, answers: answers as Subject4dResult["answers"], answeredAt: new Date().toISOString() };
}
