/** 0—100 绝对分：V2 满分 24（12 + 净分/2），V1 满分 12。 */
function toScore100(dims: DiscDims, version?: 2): Score100 {
  const k = version === 2 ? 100 / 24 : 100 / 12;
  return {
    D: Math.round(dims.D * k),
    I: Math.round(dims.I * k),
    S: Math.round(dims.S * k),
    C: Math.round(dims.C * k),
  };
}

function ranked(s: Score100): DiscType[] {
  return [...DIMS].sort((a, b) => s[b] - s[a] || RING[a] - RING[b]);
}

/** 主导维在 D-I-S-C 环上的距离：0 同型 / 1 相邻 / 2 对角。 */
function ringGap(a: DiscType, b: DiscType): 0 | 1 | 2 {
  const d = Math.abs(RING[a] - RING[b]);
  return (d > 2 ? 4 - d : d) as 0 | 1 | 2;
}

function relationWord(parent: DiscType, child: DiscType): string {
  const g = ringGap(parent, child);
  return g === 0 ? "同一格" : g === 1 ? "相邻型" : "对角型（方向相反）";
}

