function parentOf(label: string): { name: string; teenCall: string } {
  const l = label.trim();
  if (/爸|父/.test(l)) return { name: l || "爸爸", teenCall: "你爸" };
  if (/妈|母/.test(l)) return { name: l || "妈妈", teenCall: "你妈" };
  return { name: l || "家长", teenCall: `你${l || "家长"}` };
}

