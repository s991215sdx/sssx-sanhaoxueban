export function buildCommKit(input: CommKitInput): CommKitResult {
  const studentScore = input.disc ? toScore100(input.disc.dims, input.disc.version) : null;
  const sRank = studentScore ? ranked(studentScore) : null;

  const student: KitMember | null =
    studentScore && sRank
      ? {
          key: "student",
          name: input.studentName?.trim() || "孩子",
          teenCall: "你",
          kind: "student",
          type: sRank[0],
          second: sRank[1],
          score: studentScore,
        }
      : null;

  const parents: KitMember[] = (input.parents ?? [])
    .filter((p) => p?.result?.dims)
    .map((p, i) => {
      const s = toScore100(p.result.dims, p.result.version);
      const r = ranked(s);
      const nm = parentOf(p.label ?? "");
      return {
        key: `parent-${i}`,
        name: nm.name,
        teenCall: nm.teenCall,
        kind: "parent" as const,
        type: r[0],
        second: r[1],
        score: s,
      };
    });

  const books: KitBook[] = [
    buildTrio(student, parents, input.grade),
    buildStudentBook(student, parents),
    buildMeBook(student),
    ...buildParentBooks(parents),
  ];

  return {
    books,
    members: [student, ...parents].filter(Boolean) as KitMember[],
    trioTitle: parents.length >= 2 ? "三人版" : parents.length === 1 ? "两人版" : "家庭版",
  };
}

