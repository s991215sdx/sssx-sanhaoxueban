/** 一对关系的开场句：环距决定说法，不能把「最难拆」套到所有组合上。 */
function pairLead(parent: DiscType, child: DiscType, second = false): string {
  const g = ringGap(parent, child);
  if (g === 2)
    return `${parent} 与 ${child} 是对角型（方向相反）：差两维，十六格里最难拆的一格——不难在吵得凶，难在根本不吵`;
  if (g === 0) return `${parent} 与 ${child} 是同一格：你们要的东西一样，所以更容易撞在同一个位置上`;
  return second
    ? `${parent} 与 ${child} 是相邻型：差一维，能互相接住。这一对的危险不是冲突，是结盟`
    : `${parent} 与 ${child} 是相邻型：差一维，本来能互补——前提是两个人别在同一件事上同时退`;
}

