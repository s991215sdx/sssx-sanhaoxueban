/* ---------------- 测评个性化加成 ---------------- */

export interface PersonalCtx {
  /** 得分率 0-100（无成绩为 null） */
  pct?: number | null;
  /** 趋势 up/down/flat */
  trend?: "up" | "down" | "flat" | null;
  /** 与该学科最相关的多元智能分（0-100，无测评为 null） */
  ability?: number | null;
  /** 学业差距（目标-最近，无目标为 null） */
  gap?: number | null;
}

/** 依据成绩与多元智能，为该学科动态生成一条个性化建议（拼在通用方法之前）。 */
export function personalTip(subject: string, ctx: PersonalCtx): string | null {
  const parts: string[] = [];
  if (ctx.pct != null) {
    if (ctx.pct >= 80 && ctx.trend === "up") parts.push(`${subject}当前处于上升期且得分率 ${Math.round(ctx.pct)}%——保持现有节奏，适当超前学半个学期`);
    else if (ctx.pct >= 80) parts.push(`${subject}底子扎实（得分率 ${Math.round(ctx.pct)}%）——把精力匀给弱科，此科保持手感即可`);
    else if (ctx.pct < 60) parts.push(`${subject}当前得分率 ${Math.round(ctx.pct)}% 偏低——先回到课本与基础题，别急着刷难题`);
    else parts.push(`${subject}得分率 ${Math.round(ctx.pct)}% 处于中段——突破点在「会而不对」的环节，重视错题归因`);
  }
  if (ctx.ability != null && ctx.ability >= 75 && (ctx.pct == null || ctx.pct < 80)) {
    parts.push(`多元智能显示相关能力 ${Math.round(ctx.ability)} 分不低——这科学得吃力更像方法问题，优先换学法而不是加时间`);
  } else if (ctx.ability != null && ctx.ability < 55 && ctx.pct != null && ctx.pct < 65) {
    parts.push(`相关智能测评 ${Math.round(ctx.ability)} 分偏低——这科需要更多拆解与重复，放慢节奏、小步快跑`);
  }
  if (ctx.gap != null && ctx.gap >= 15) parts.push(`与目标差 ${Math.round(ctx.gap)} 分：先锁定丢分最多的一个题型，集中两周攻克`);
  return parts.length > 0 ? parts.slice(0, 2).join("；") + "。" : null;
}

